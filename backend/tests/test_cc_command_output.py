def test_output_written_later_shows_after_the_next_read_and_never_under_another_command(tmp_path: Path) -> None:
    """Event order 1: the file grows while it is read."""
    path = _write(
        tmp_path,
        [
            _user("c1", CAVEAT, 0),
            _user("c2", _command("/mcp"), 1, parent="c1"),
        ],
    )
    (marker,) = _markers(_read(path))
    assert marker.get("command_output") is None

    _append(path, [_user("c3", _stdout("MCP output B52MCPTOKEN"), 2, parent="c2")])
    (marker,) = _markers(_read(path))
    assert marker["command_output"] == "MCP output B52MCPTOKEN"

    _append(path, [_user("c4", CAVEAT, 3, parent="c3"), _user("c5", _command("/model"), 4, parent="c4")])
    markers = _markers(_read(path))
    assert [(m["slash_command"], m.get("command_output")) for m in markers] == [
        ("/mcp", "MCP output B52MCPTOKEN"),
        ("/model", None),
    ]

    _append(path, [_user("c6", _stdout(MODEL_STDOUT_RAW), 5, parent="c5")])
    markers = _markers(_read(path))
    assert [(m["slash_command"], m.get("command_output")) for m in markers] == [
        ("/mcp", "MCP output B52MCPTOKEN"),
        ("/model", MODEL_STDOUT),
    ]


