"""B52 (issue #52), parts A and B: Claude Code's own rows show as what they are.

* A: the output of a local slash command is part of the command's marker
  (``command_output``, D1), without tags or ANSI codes (D2). The newer
  ``system`` / ``local_command`` rows give the same markers as the older
  user rows. stderr is kept and marked as an error.
* B: a ``!`` command is one shell message (``shell_command`` and
  ``shell_output``), and an injected notice is a notice row
  (``notice_kind``). No text keeps the XML tags.

The list's message count does not change, and command output is searchable.
All data is synthetic.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

CAVEAT = (
    "<local-command-caveat>Caveat: The messages below were generated by the "
    "user while running local commands. DO NOT respond to these messages or "
    "otherwise consider them in your response unless the user explicitly "
    "asks you to.</local-command-caveat>"
)
SESSION = "b52a0000-0000-4000-8000-000000000001"
PROJECT = "-tmp-b52"

# /model output as Claude Code writes it: bold and color escape codes.
MODEL_STDOUT_RAW = "Set model to \x1b[1mFable 5.1\x1b[22m (claude-fable-5-1) B52MODELTOKEN"
MODEL_STDOUT = "Set model to Fable 5.1 (claude-fable-5-1) B52MODELTOKEN"

NOTICE_KINDS = ["task-notification", "bash-notification", "scheduled-task", "system-reminder"]
TAGS = (
    "<local-command-",
    "</local-command-",
    "<bash-",
    "</bash-",
    "<task-notification>",
    "<bash-notification>",
    "<scheduled-task>",
    "<system-reminder>",
)


def _ts(n: int) -> str:
    return f"2026-11-01T10:{n // 60:02d}:{n % 60:02d}Z"


def _user(uuid: str, text: str, n: int, parent: str | None = None) -> dict[str, Any]:
    return {
        "type": "user",
        "uuid": uuid,
        "parentUuid": parent,
        "sessionId": SESSION,
        "cwd": "/tmp/b52",
        "timestamp": _ts(n),
        "message": {"role": "user", "content": text},
    }


def _system(uuid: str, text: str, n: int, parent: str | None = None) -> dict[str, Any]:
    """A newer Claude Code row: the text is in the top-level ``content``."""
    return {
        "type": "system",
        "subtype": "local_command",
        "uuid": uuid,
        "parentUuid": parent,
        "sessionId": SESSION,
        "cwd": "/tmp/b52",
        "gitBranch": "main",
        "version": "2.1.0",
        "userType": "external",
        "isSidechain": False,
        "isMeta": False,
        "level": "info",
        "timestamp": _ts(n),
        "content": text,
    }


def _assistant(uuid: str, text: str, n: int, parent: str | None = None, model: str = "claude-opus-5-5") -> dict[str, Any]:
    return {
        "type": "assistant",
        "uuid": uuid,
        "parentUuid": parent,
        "sessionId": SESSION,
        "timestamp": _ts(n),
        "message": {
            "id": f"msg_{uuid}",
            "role": "assistant",
            "model": model,
            "content": [{"type": "text", "text": text}],
        },
    }


def _command(name: str, args: str = "") -> str:
    return (
        f"<command-name>{name}</command-name>\n"
        f"            <command-message>{name.lstrip('/')}</command-message>\n"
        f"            <command-args>{args}</command-args>"
    )


def _stdout(text: str) -> str:
    return f"<local-command-stdout>{text}</local-command-stdout>"


def _stderr(text: str) -> str:
    return f"<local-command-stderr>{text}</local-command-stderr>"


def _write(tmp_path: Path, entries: list[dict[str, Any]], session: str = SESSION) -> Path:
    path = tmp_path / "claude" / "projects" / PROJECT / f"{session}.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(e) + "\n" for e in entries), encoding="utf-8")
    return path


def _append(path: Path, entries: list[dict[str, Any]]) -> None:
    with path.open("a", encoding="utf-8") as f:
        f.writelines(json.dumps(e) + "\n" for e in entries)


def _read(path: Path) -> list[dict[str, Any]]:
    from backend.claude_code_reader import read_claude_code_conversation

    detail = read_claude_code_conversation(path)
    assert detail is not None
    return detail["chat_messages"]


def _markers(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [m for m in messages if m.get("slash_command")]


def _texts(message: dict[str, Any]) -> list[str]:
    out = [message.get("text") or ""]
    out += [b.get("text") or "" for b in message.get("content") or [] if isinstance(b, dict)]
    return out


def _model_run(form: str) -> list[dict[str, Any]]:
    """A /model run, then a reply. ``form`` is "user" or "system"."""
    row = _user if form == "user" else _system
    return [
        _user("u0", "Hello, please help.", 0),
        _assistant("a0", "Sure.", 1, parent="u0"),
        row("c1", CAVEAT, 2, parent="a0"),
        row("c2", _command("/model"), 3, parent="c1"),
        row("c3", _stdout(MODEL_STDOUT_RAW), 4, parent="c2"),
        _user("u1", "Now continue.", 5, parent="c3"),
        _assistant("a1", "Continuing.", 6, parent="u1", model="claude-fable-5-1"),
    ]


def _marker_view(marker: dict[str, Any]) -> dict[str, Any]:
    keys = ("slash_command", "text", "is_command_marker", "command_output", "command_output_is_error")
    return {k: marker.get(k) for k in keys}


