    markers = _markers(_read(_write(tmp_path, entries)))
    assert [(m["slash_command"], m["command_output"]) for m in markers] == [
        ("/mcp", "MCP output B52MCPTOKEN"),
        ("/model", MODEL_STDOUT),
    ]


