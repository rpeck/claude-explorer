def test_merged_streaming_chunks_take_the_model_of_the_first_chunk_that_has_one(tmp_path: Path) -> None:
    entries = [
        _user("u1", "Think first.", 0),
        _chunk("x1", "msg_x", 1, None, {"type": "thinking", "thinking": "Hmm."}, "u1"),
        _chunk("x2", "msg_x", 2, "claude-fable-5-1", {"type": "text", "text": "Answer."}, "x1"),
        _chunk("x3", "msg_x", 3, "claude-opus-5-5", {"type": "text", "text": "More."}, "x2"),
    ]
    (reply,) = [m for m in _read_cc(_write_cc(tmp_path, entries)) if m["sender"] == "assistant"]
    assert reply["model"] == "claude-fable-5-1"


def test_replies_before_a_model_switch_name_the_old_model_and_replies_after_it_the_new_one(tmp_path: Path) -> None:
    messages = _read_cc(_write_cc(tmp_path, _switch_session()))
    sequence = [
        ("model", m["model"]) if m["sender"] == "assistant" else ("output", m.get("command_output"))
        for m in messages
        if m["sender"] == "assistant" or m.get("slash_command") == "/model"
    ]
    assert sequence == [
        ("model", "claude-opus-5-5"),
        ("model", "claude-opus-5-5"),
        ("output", "Set model to Fable 5.1 (claude-fable-5-1)"),
        ("model", "claude-fable-5-1"),
        ("model", "<synthetic>"),
    ]


