def _md_senders(md: str) -> list[str]:
    return re.findall(r"^\*\*(.+?):\*\* \*", md, flags=re.MULTILINE)


def _html_senders(html: str) -> list[str]:
    return re.findall(r'<div class="message-header">\s*(.*?) <span class="timestamp">', html)


def _bundle_markdown(data: bytes) -> str:
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return next(z.read(n).decode() for n in z.namelist() if n.endswith(".md"))


