def test_each_cowork_assistant_message_has_the_model_of_its_row(tmp_path: Path) -> None:
    from backend.cowork_reader import read_cowork_conversation

    def row(kind: str, uuid: str, n: int, content: Any, model: str | None = None) -> dict[str, Any]:
        message: dict[str, Any] = {"role": kind, "content": content}
        if model:
            message.update(model=model, id=f"msg_{uuid}", type="message")
        return {
            "type": kind,
            "uuid": uuid,
            "session_id": COWORK,
            "parent_tool_use_id": None,
            "message": message,
            "_audit_timestamp": f"2026-11-01T13:00:{n:02d}.000Z",
        }

    session_dir = tmp_path / "d_dep" / "o_org" / f"local_{COWORK}"
    session_dir.mkdir(parents=True)
    rows = [
        row("user", "cu1", 0, "Hello Cowork."),
        row("assistant", "ca1", 1, [{"type": "text", "text": "Opus here."}], "claude-opus-5-5"),
        row("user", "cu2", 2, "Again."),
        row("assistant", "ca2", 3, [{"type": "text", "text": "Fable here."}], "claude-fable-5-1"),
    ]
    (session_dir / "audit.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")
    detail = read_cowork_conversation(session_dir)
    assert detail is not None
    models = [m.get("model") for m in detail["chat_messages"] if m["sender"] == "assistant"]
    assert models == ["claude-opus-5-5", "claude-fable-5-1"]


