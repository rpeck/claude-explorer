def test_model_names_imports_only_the_standard_library() -> None:
    """The MCPB bundle stays small: the module has no third-party imports."""
    import backend.model_names as mod

    tree = ast.parse(Path(mod.__file__).read_text(encoding="utf-8"))
    roots = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots |= {a.name.split(".")[0] for a in node.names}
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            roots.add(node.module.split(".")[0])
    assert roots - set(sys.stdlib_module_names) - {"__future__"} == set()


