"""B52 (issue #52), part C: each reply names its model.

* ``backend.model_names``: ``model_display_name`` ("claude-opus-5-5" gives
  "Opus 5.5") and ``reply_label`` ("Claude Opus 5.5"; "<synthetic>" gives
  "Claude Code"; no model gives the source's ``assistant_label``).
* Claude Code and Cowork: each assistant message has ``model`` from its row
  (the first streaming chunk that has one).
* Claude Desktop and Codex (D5): ``store.get_conversation`` gives each
  assistant message the conversation's model, with
  ``model_from_conversation`` set.
* One name everywhere: the Markdown, bundle, and PDF exports and the MCP
  server's ``get_messages`` use ``reply_label``.

All data is synthetic.
"""

